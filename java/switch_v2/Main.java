class SwitchDemo { 
    public static void main(String[] args) { 
 
        int springMonth = 2;
        switch (springMonth ) { 
            case 1:  System.out.println("March"); break; 
            case 2:  System.out.println("April"); break; 
            case 3:  System.out.println("May"); break; 
            default: System.out.println("Invalid month"); break; 
        } 
    } 
}